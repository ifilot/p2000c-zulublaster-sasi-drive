BEGIN	ORG	103H
INITIL	JMP	INITIU			;UART/USART INITIALATION ENTRY POINT
INSPORT JMP	INSPRU			;STATUS PORT READ 40 BIT
;
;
;
	PUSH	B
	IN	TPS
	MOV	C,A
	MVI	B,4			;PRE-SET TRANSMITTER EMPTY BIT
	ANI	1			;CHK DATA RECEIVED
	JZ	CHKTXRD
	MVI	A,2			;SET RECEIVER READY BIT
	ORA	B
	MOV	B,A
CHKTXRD EQU	$
	MOV	A,C
	ANI	4			;CHK TRANSMITTER READY
	JZ	DONE
	MVIENTRY POINT
ERRSET	JMP	ERRSTU			;UART/USART ERROR RESET ENTRY POINT
INPORT	JMP	INPRTU			;READ DATA PORT ENTRY POINT
OUTPORT JMP	OUTPRU			;WRITE DATA PORT ENTRY POINT
DUART	JMP	DUARTU
DUARTU	RET
;
;
;
;			IF YOU WISH TO USE OTHER REGISTERS SUCH AS 	A,1			;SET TRANSMITTER READY
	ORA	B
	MOV	B,A
DONE	EQU	$
	MOV	A,B			;BITS ARE NOW SET FOR BSTAM
	POP	B
	RET		;RETURN TO BSTAM
